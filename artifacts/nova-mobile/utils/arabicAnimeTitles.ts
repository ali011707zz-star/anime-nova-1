/**
 * دالة استخراج الاسم العربي الصحيح بناءً على ID الأنمي أو اسمه بالإنجليزية / الرومانجي
 */
export function getKnownArabicAnimeTitle(
  id?: number | null,
  english?: string | null,
  romaji?: string | null
): string | null {
  if (id && KNOWN_ARABIC_TITLES_BY_ID[id]) {
    return KNOWN_ARABIC_TITLES_BY_ID[id];
  }
  const candidate = (english || romaji || "").trim();
  if (!candidate) return null;
  for (const { regex, arabic } of TITLE_PATTERN_MAP) {
    if (regex.test(candidate)) {
      return arabic;
    }
  }
  return null;
}
